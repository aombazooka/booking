$pass = 0; $fail = 0;
foreach ($cases as [$date, $phase, $day, $month, $second8]) {
    $r = tl_lunar_date($date);
    if ($r === null) {
        echo "FAIL $date → คำนวณไม่ได้ (null)\n"; $fail++; continue;
    }
    $ok = $r['phase'] === $phase && $r['day'] === $day && $r['month'] === $month && $r['second8'] === $second8;
    if ($ok) {
        $pass++;
    } else {
        $fail++;
        printf("FAIL %s → ได้ %s %d ค่ำ เดือน %d%s | ควรเป็น %s %d ค่ำ เดือน %d%s\n",
            $date, $r['phase'], $r['day'], $r['month'], $r['second8'] ? ' (หลัง)' : '',
            $phase, $day, $month, $second8 ? ' (หลัง)' : '');
    }
}

